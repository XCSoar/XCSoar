RGB8Color
LookupTerrainColor(unsigned ramp, int height, bool water) noexcept
{
  /* Same water blue as RasterRenderer's colour table. */
  if (water)
    return {85, 160, 255};

  if (ramp >= TerrainRendererSettings::NUM_RAMPS)
    ramp = 0;
  if (height < 0)
    height = 0;
  return ColorRampLookup(height, &terrain_ramps[ramp]);
}
